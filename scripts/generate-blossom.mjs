/**
 * Author-time SDF for the official OpenAI Blossom. Run: node scripts/generate-blossom.mjs
 * Source: https://openai.com/brand/ (Blossom_Light.svg, first filled path; guides omitted).
 * sharp is already supplied by Next.js. Nothing is rasterized or fetched at runtime.
 */
import { readFile, writeFile } from 'node:fs/promises';
import sharp from 'sharp';

const size = 256;
const supersample = 4;
const resolution = size * supersample;
const extent = 1.1;
const range = 0.2;
const source = await readFile(new URL('../assets/openai-blossom.svg', import.meta.url));
const raster = await sharp(source).resize(resolution, resolution).ensureAlpha().raw().toBuffer();
const mask = new Uint8Array(resolution * resolution);
for (let i = 0; i < mask.length; i++) mask[i] = raster[i * 4 + 3] >= 128 ? 1 : 0;

// Exact squared Euclidean distance transform, separable in x and y. The lower envelope of
// parabolas makes each pass linear rather than scanning every source pixel for every cell.
function transform1d(input, output) {
  const n = input.length;
  const v = new Int32Array(n);
  const z = new Float64Array(n + 1);
  let k = 0;
  z[0] = -Infinity;
  z[1] = Infinity;
  for (let q = 1; q < n; q++) {
    let s = (input[q] + q * q - (input[v[k]] + v[k] * v[k])) / (2 * (q - v[k]));
    while (s <= z[k]) {
      k--;
      s = (input[q] + q * q - (input[v[k]] + v[k] * v[k])) / (2 * (q - v[k]));
    }
    k++;
    v[k] = q;
    z[k] = s;
    z[k + 1] = Infinity;
  }
  k = 0;
  for (let q = 0; q < n; q++) {
    while (z[k + 1] < q) k++;
    output[q] = (q - v[k]) * (q - v[k]) + input[v[k]];
  }
}

function distanceTo(value) {
  const field = new Float64Array(mask.length);
  const line = new Float64Array(resolution);
  const result = new Float64Array(resolution);
  for (let y = 0; y < resolution; y++) {
    for (let x = 0; x < resolution; x++) line[x] = mask[y * resolution + x] === value ? 0 : 1e12;
    transform1d(line, result);
    field.set(result, y * resolution);
  }
  for (let x = 0; x < resolution; x++) {
    for (let y = 0; y < resolution; y++) line[y] = field[y * resolution + x];
    transform1d(line, result);
    for (let y = 0; y < resolution; y++) field[y * resolution + x] = result[y];
  }
  return field;
}

const toInk = distanceTo(1);
const toPaper = distanceTo(0);
const pixels = new Uint8Array(size * size);
const unitsPerPixel = (extent * 2) / resolution;
for (let y = 0; y < size; y++) {
  for (let x = 0; x < size; x++) {
    // Average the four central subpixels to locate the low-resolution texel center exactly.
    let distance = 0;
    for (let sy = 1; sy <= 2; sy++) {
      for (let sx = 1; sx <= 2; sx++) {
        const i = (y * supersample + sy) * resolution + x * supersample + sx;
        const signed = mask[i] ? -Math.sqrt(toPaper[i]) + 0.5 : Math.sqrt(toInk[i]) - 0.5;
        distance += signed * unitsPerPixel * 0.25;
      }
    }
    pixels[y * size + x] = Math.round(Math.max(0, Math.min(1, 0.5 + distance / (range * 2))) * 255);
  }
}

const generated = `/** Generated by scripts/generate-blossom.mjs from assets/openai-blossom.svg. */\nexport const BLOSSOM_SIZE = ${size};\nexport const BLOSSOM_EXTENT = ${extent};\nexport const BLOSSOM_RANGE = ${range};\nexport const BLOSSOM_BASE64 =\n  '${Buffer.from(pixels).toString('base64')}';\n`;
await writeFile(new URL('../src/components/gpu/blossom-data.ts', import.meta.url), generated);
console.log(`Generated ${size} x ${size} R8 Blossom SDF (${pixels.length} bytes).`);
